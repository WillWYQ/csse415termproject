def _no_round2(_: Dict) -> Dict:
    """Sentinel: skip Round 2."""
    return {}


def _refine_knn(best: Dict) -> Dict:
    """Zoom in around the best k with step=1, keep best weight & metric."""
    k     = int(best["n_neighbors"])
    return {
        "n_neighbors": zoom_int(k, step=1, n=3),
        "weights":     [best["weights"]],
        "metric":      [best["metric"]],
    }


def _refine_ridge(best: Dict) -> Dict:
    """Zoom in on log(C) ±0.5 decades."""
    return {"C": zoom_log(best["C"], n=5, radius_decades=0.5)}


def _refine_lasso(best: Dict) -> Dict:
    return {"C": zoom_log(best["C"], n=5, radius_decades=0.5)}


def _refine_svm(best: Dict) -> Dict:
    return {
        "estimator__C":    zoom_log(best["estimator__C"], n=5, radius_decades=0.5),
        "estimator__loss": [best["estimator__loss"]],
    }


def _refine_dt(best: Dict) -> Dict:
    d = best["max_depth"]
    return {
        "max_depth":         zoom_int(d, step=1, n=2) if d is not None
                             else [6, 8, 10, 12, None],
        "min_samples_split": [best["min_samples_split"]],
        "min_samples_leaf":  [best["min_samples_leaf"]],
    }


def _refine_rf(best: Dict) -> Dict:
    n = int(best["n_estimators"])
    d = int(best["max_depth"])
    return {
        "n_estimators": zoom_int(n, step=1, n=10),
        "max_depth":    zoom_int(d, step=1, n=2),
    }


def _refine_gbt(best: Dict) -> Dict:
    n  = int(best["n_estimators"])
    d  = int(best["max_depth"])
    lr = float(best["learning_rate"])
    return {
        "learning_rate": [lr],
        "n_estimators":  zoom_int(n, step=10, n=3),
        "max_depth":     zoom_int(d, step=1,  n=2),
    }


def _refine_kernel_svm(best: Dict) -> Dict:
    """
    Zoom in on gamma and C independently (±0.75 log-decades, 9 points each).
    n_components is held fixed at the Round-1 value — retuning it in Round 2
    would be too expensive because it controls the size of the feature map.

    Round-2 grid size: 9 × 9 × 1 = 81 combos (× cv folds).
    """
    return {
        "nystroem__gamma":        zoom_log(best["nystroem__gamma"],
                                           n=4, radius_decades=0.75),
        "clf__C":                 zoom_log(best["clf__C"],
                                           n=4, radius_decades=0.75),
        "nystroem__n_components": [best["nystroem__n_components"]],
    }


