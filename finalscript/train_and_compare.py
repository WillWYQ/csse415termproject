# Feature importance (tree models)
# ──────────────────────────────────────────────────────────────────────────────

def _extract_feature_importance(
    train_results: List[TrainResult],
    feature_names: List[str],
    top_n: int = 10,
) -> Optional[pd.DataFrame]:
    """
    Build a comparison DataFrame of feature importances for tree-based models
    (Decision Tree, Random Forest, Gradient Boosting).

    Returns None if no tree model was trained.
    """
    tree_models = {
        r.name: r.best_estimator
        for r in train_results
        if hasattr(r.best_estimator, "feature_importances_")
    }

    if not tree_models:
        return None

    fi_df = pd.DataFrame({"Feature": feature_names})
    for name, est in tree_models.items():
        fi_df[name] = est.feature_importances_

    model_cols = list(tree_models.keys())
    primary    = model_cols[0]
    fi_df      = fi_df.sort_values(primary, ascending=False).head(top_n)

    return fi_df.reset_index(drop=True)


# ──────────────────────────────────────────────────────────────────────────────
# Main entry point
# ──────────────────────────────────────────────────────────────────────────────

def train_and_compare(
    data: PreparedData,
    specs: List[ModelSpec],
    config: Optional[Dict] = None,
) -> CompareResult:
    """
    Train every model in *specs*, evaluate on the test set, and return a
    CompareResult with the ranked comparison table and all per-model artefacts.

    Parameters
    ----------
    data   : PreparedData from prepare()
    specs  : list of ModelSpec (use build_model_specs() as a starting point)
    config : optional dict; recognised keys:
               cv          int   cross-validation folds       (default 5)
               scoring     str   sklearn scoring string       (default 'accuracy')
               n_examples  int   individual prediction count  (default 1)
               top_n_fi    int   feature importance top-N     (default 10)
               baseline_strategy  'most_frequent' | 'stratified'
    """
    if config is None:
        config = {}

    cv            : int = config.get("cv",            5)
    scoring       : str = config.get("scoring",       "accuracy")
    n_examples    : int = config.get("n_examples",    1)
    top_n_fi      : int = config.get("top_n_fi",      10)

    # ── Baseline ──────────────────────────────────────────────────────────────
    most_frequent = int(data.y_train.value_counts().idxmax())
    y_pred_base   = np.full(len(data.y_test), most_frequent)
    baseline_acc  = float(accuracy_score(data.y_test, y_pred_base))
    print(f"\n  Baseline (most-frequent class = {data.label_map.get(most_frequent, most_frequent)})"
          f"  test accuracy: {baseline_acc:.4f}")

    # ── Train each model ──────────────────────────────────────────────────────
    train_results: List[TrainResult] = []
    for spec in specs:
        result = _train_one(spec, data, cv, scoring)
        train_results.append(result)

    # ── Build ranked comparison table ─────────────────────────────────────────
    rows = [
        {
            "Model":         "Baseline (Most Frequent)",
            "Dataset":       "—",
            "Val Acc (R1)":  "—",
            "Val Acc (R2)":  "—",
            "Test Accuracy": baseline_acc,
            "Time (s)":      "—",
        }
    ]
    for r in train_results:
        rows.append({
            "Model":         r.name,
            "Dataset":       r.dataset,
            "Val Acc (R1)":  f"{r.val_accuracy_1:.4f}",
            "Val Acc (R2)":  f"{r.val_accuracy_2:.4f}",
            "Test Accuracy": r.test_accuracy,
            "Time (s)":      f"{r.train_seconds:.1f}",
        })

    comparison_df = (
        pd.DataFrame(rows)
        .sort_values("Test Accuracy", ascending=False)
        .reset_index(drop=True)
    )
    comparison_df.index = comparison_df.index + 1
    comparison_df.index.name = "Rank"

    # Pretty-format test accuracy only AFTER sorting
    comparison_df_display = comparison_df.copy()
    comparison_df_display["Test Accuracy"] = (
        comparison_df_display["Test Accuracy"].map("{:.4f}".format)
    )

    # ── Per-model classification reports ──────────────────────────────────────
    print("\n\n" + "═" * 62)
    print("  CLASSIFICATION REPORTS")
    print("═" * 62)
    for r in train_results:
        print(f"\n── {r.name} ──")
        print(r.class_report)

    # ── Individual prediction analysis ────────────────────────────────────────
    print("\n\n" + "═" * 62)
    print("  INDIVIDUAL PREDICTION ANALYSIS")
    print("═" * 62)
    for r in train_results:
        analyze_predictions(r, data, n_examples=n_examples)

    # ── Feature importance (tree models) ──────────────────────────────────────
    fi_df = _extract_feature_importance(
        train_results, data.feature_names, top_n=top_n_fi
    )
    if fi_df is not None:
        print("\n\n" + "═" * 62)
        print(f"  FEATURE IMPORTANCE — top {top_n_fi} (Base feature set)")
        print("═" * 62)
        print(fi_df.to_string(index=False))

    # ── Build models dict  (name → fitted estimator, ordered by rank) ────────
    ranked_names = list(comparison_df["Model"])          # best-first order
    models: Dict[str, Any] = {}
    for name in ranked_names:
        if name == "Baseline (Most Frequent)":
            continue
        match = next((r for r in train_results if r.name == name), None)
        if match:
            models[name] = match.best_estimator

    # ── Final summary ─────────────────────────────────────────────────────────
    result = CompareResult(
        comparison_df     = comparison_df,
        train_results     = train_results,
        baseline_accuracy = baseline_acc,
        models            = models,
    )
    result.summary()
    return result