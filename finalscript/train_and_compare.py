@dataclass
class ModelSpec:
    """
    Everything train_and_compare needs to train and tune one model.

    Attributes
    ----------
    name        : display name used in the comparison table
    estimator   : unfitted sklearn estimator (or Pipeline)
    dataset     : 'FE' (feature-engineered) | 'base' (pre-engineering)
    param_grid_1: coarse grid for Round 1
    refine_fn   : callable(best_params_1) → fine param_grid for Round 2
                  Return {} to skip Round 2 (e.g., Logistic Regression plain)
    cv          : cross-validation folds (default uses config value)
    scoring     : metric string (default uses config value)
    """
    name:         str
    estimator:    Any
    dataset:      str                            # 'FE' | 'base'
    param_grid_1: Dict[str, Any]
    refine_fn:    Callable[[Dict], Dict]
    cv:           Optional[int]  = None          # None → use global config
    scoring:      Optional[str]  = None          # None → use global config


@dataclass
class TrainResult:
    """Artefacts produced for one model after both grid-search rounds."""
    name:          str
    dataset:       str
    best_estimator: Any
    best_params_1: Dict
    best_params_2: Dict
    cv1_results:   pd.DataFrame
    cv2_results:   pd.DataFrame                  # empty if refine_fn returns {}
    val_accuracy_1: float
    val_accuracy_2: float                        # same as _1 if no Round 2
    test_accuracy: float
    y_pred:        np.ndarray
    class_report:  str
    train_seconds: float


@dataclass
class CompareResult:
    """
    Aggregated output of train_and_compare().

    Quick-access attributes
    -----------------------
    result.models                    # Dict[name → best_estimator]
    result.best_model                # the single best fitted estimator
    result.best_model_name           # its display name
    result["Random Forest (tuned)"]  # estimator by name (bracket syntax)
    """
    comparison_df:     pd.DataFrame      # ranked by test accuracy
    train_results:     List[TrainResult]
    baseline_accuracy: float
    models:            Dict[str, Any]    # name → fitted best_estimator

    # ── convenience accessors ────────────────────────────────────────────────

    @property
    def best_model_name(self) -> str:
        """Name of the model with the highest test accuracy."""
        return self.comparison_df.iloc[0]["Model"]

    @property
    def best_model(self) -> Any:
        """Fitted estimator with the highest test accuracy."""
        return self.models[self.best_model_name]

    def __getitem__(self, name: str) -> Any:
        """result['Model Name'] → fitted estimator."""
        if name not in self.models:
            available = list(self.models.keys())
            raise KeyError(
                f"No model named {name!r}.  Available: {available}"
            )
        return self.models[name]

    def summary(self) -> None:
        """Print the ranked comparison table."""
        print("\n" + "=" * 62)
        print(f"{'Rank':<5} {'Model':<35} {'Dataset':<7} {'TestAcc':>8}")
        print("=" * 62)
        for rank, row in self.comparison_df.iterrows():
            marker = " ◄" if row["Model"] == self.best_model_name else ""
            print(
                f"{rank:<5} {row['Model']:<35} {row['Dataset']:<7}"
                f" {row['Test Accuracy']:>8.4f}{marker}"
            )
        print("=" * 62)


