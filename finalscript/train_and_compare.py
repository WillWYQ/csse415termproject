def analyze_predictions(
    result: TrainResult,
    data: PreparedData,
    n_examples: int = 1,
) -> None:
    """
    For a given TrainResult, print the *n_examples* most-confident correct
    predictions (best) and *n_examples* most-confident wrong predictions (worst).

    Requires the estimator to support predict_proba.
    """
    X_test, _ = _select_dataset(data, result.dataset)
    y_test     = data.y_test.values
    y_pred     = result.y_pred

    try:
        proba = result.best_estimator.predict_proba(X_test)
    except AttributeError:
        print(f"  [{result.name}] predict_proba not available — skipping.")
        return

    # confidence = probability assigned to the TRUE class
    confidence = proba[np.arange(len(y_test)), y_test.astype(int)]

    correct_mask   = y_pred == y_test
    incorrect_mask = ~correct_mask

    label_map = data.label_map

    print(f"\n{'═'*62}")
    print(f"  Individual prediction analysis : {result.name}")
    print(f"{'═'*62}")

    for tag, mask, order in [
        ("BEST (correct, highest confidence)",   correct_mask,   "descending"),
        ("WORST (wrong,   highest confidence)",  incorrect_mask, "descending"),
    ]:
        idxs = np.where(mask)[0]
        if len(idxs) == 0:
            print(f"  {tag}: none found.")
            continue

        ranked = idxs[np.argsort(confidence[idxs])[::-1]][:n_examples]
        print(f"\n  ── {tag} ──")

        for i, idx in enumerate(ranked, 1):
            true_lbl  = label_map.get(int(y_test[idx]),  str(y_test[idx]))
            pred_lbl  = label_map.get(int(y_pred[idx]),  str(y_pred[idx]))
            conf      = confidence[idx]
            print(
                f"    #{i}  index={idx}"
                f"  true={true_lbl}"
                f"  predicted={pred_lbl}"
                f"  confidence={conf:.4f}"
            )
            # Show numeric feature values for this record
            num_vals = X_test.iloc[idx][data.numeric_cols]
            print("    numeric features:")
            for col, val in num_vals.items():
                print(f"      {col:<35s}: {val:+.3f}")


