def _select_dataset(
    data: PreparedData, dataset: str
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Return (X_train, X_test) for the requested dataset tag."""
    if dataset == "FE":
        return data.X_train_FE, data.X_test_FE
    if dataset == "base":
        return data.X_train_base, data.X_test_base
    raise ValueError(f"Unknown dataset tag '{dataset}'. Use 'FE' or 'base'.")


def _run_grid_search(
    estimator: Any,
    param_grid: Dict,
    X_train: pd.DataFrame,
    y_train: pd.Series,
    cv: int,
    scoring: str,
) -> Tuple[Any, Dict, float, pd.DataFrame]:
    """
    Run a single GridSearchCV pass.

    Returns
    -------
    (best_estimator, best_params, best_score, cv_results_df)
    """
    gs = GridSearchCV(
        estimator,
        param_grid=param_grid,
        scoring=scoring,
        cv=cv,
        return_train_score=True,
        n_jobs=-1,
    )
    gs.fit(X_train, y_train)
    return (
        gs.best_estimator_,
        gs.best_params_,
        float(gs.best_score_),
        pd.DataFrame(gs.cv_results_),
    )


def _fit_direct(
    estimator: Any,
    X_train: pd.DataFrame,
    y_train: pd.Series,
    cv: int,
    scoring: str,
) -> Tuple[Any, Dict, float, pd.DataFrame]:
    """
    Fit the estimator once (no hyperparameters to search).
    Returns the same 4-tuple as _run_grid_search for uniform downstream handling.
    Estimates the 'best score' with a quick 3-fold CV for comparability.
    """
    from sklearn.model_selection import cross_val_score

    estimator.fit(X_train, y_train)
    cv_scores = cross_val_score(
        estimator, X_train, y_train,
        scoring=scoring, cv=min(cv, 3), n_jobs=-1
    )
    return (
        estimator,
        {},
        float(cv_scores.mean()),
        pd.DataFrame({"mean_test_score": cv_scores}),
    )


def _train_one(
    spec: ModelSpec,
    data: PreparedData,
    cv: int,
    scoring: str,
) -> TrainResult:
    """
    Train a single model through both grid-search rounds.

    Round 1  Coarse grid (or direct fit when param_grid_1 is empty).
    Round 2  Fine grid produced by spec.refine_fn(best_params_1).
             Skipped when refine_fn returns {}.
    """
    effective_cv      = spec.cv      if spec.cv      is not None else cv
    effective_scoring = spec.scoring if spec.scoring is not None else scoring

    X_train, X_test = _select_dataset(data, spec.dataset)
    y_train, y_test = data.y_train, data.y_test

    t0 = time.perf_counter()

    print(f"\n{'─'*62}")
    print(f"  Training : {spec.name}  [{spec.dataset}]")
    print(f"{'─'*62}")

    # ── Round 1 ──────────────────────────────────────────────────────────────
    if spec.param_grid_1:
        n_combos_1 = 1
        for v in spec.param_grid_1.values():
            n_combos_1 *= len(v)
        print(f"  Round 1 : coarse grid  ({n_combos_1} combos × {effective_cv}-fold CV)")

        best_est_1, best_p1, val_acc_1, cv1_df = _run_grid_search(
            spec.estimator, spec.param_grid_1,
            X_train, y_train, effective_cv, effective_scoring,
        )
        print(f"    best params : {best_p1}")
        print(f"    val accuracy: {val_acc_1:.4f}")
    else:
        print("  Round 1 : no hyperparameters — fitting directly.")
        best_est_1, best_p1, val_acc_1, cv1_df = _fit_direct(
            spec.estimator, X_train, y_train, effective_cv, effective_scoring
        )

    # ── Round 2 ──────────────────────────────────────────────────────────────
    fine_grid = spec.refine_fn(best_p1)

    if fine_grid:
        n_combos_2 = 1
        for v in fine_grid.values():
            n_combos_2 *= len(v)
        print(f"  Round 2 : fine grid    ({n_combos_2} combos × {effective_cv}-fold CV)")

        best_est_2, best_p2, val_acc_2, cv2_df = _run_grid_search(
            spec.estimator, fine_grid,
            X_train, y_train, effective_cv, effective_scoring,
        )
        print(f"    best params : {best_p2}")
        print(f"    val accuracy: {val_acc_2:.4f}")

        # Keep Round 2 result only if it is at least as good as Round 1
        if val_acc_2 >= val_acc_1:
            final_est = best_est_2
            final_p2  = best_p2
            final_v2  = val_acc_2
        else:
            warnings.warn(
                f"[{spec.name}] Round-2 val accuracy ({val_acc_2:.4f}) is lower "
                f"than Round 1 ({val_acc_1:.4f}). Keeping Round-1 estimator.",
                UserWarning,
                stacklevel=2,
            )
            final_est = best_est_1
            final_p2  = best_p1
            final_v2  = val_acc_1
    else:
        print("  Round 2 : skipped (refine_fn returned empty grid).")
        final_est = best_est_1
        final_p2  = {}
        final_v2  = val_acc_1
        cv2_df    = pd.DataFrame()

    # ── Test-set evaluation ───────────────────────────────────────────────────
    y_pred      = final_est.predict(X_test)
    test_acc    = float(accuracy_score(y_test, y_pred))
    cls_report  = classification_report(
        y_test, y_pred,
        target_names=[data.label_map[k] for k in sorted(data.label_map)],
    )

    elapsed = time.perf_counter() - t0
    print(f"  Test accuracy : {test_acc:.4f}   ({elapsed:.1f}s total)")

    return TrainResult(
        name           = spec.name,
        dataset        = spec.dataset,
        best_estimator = final_est,
        best_params_1  = best_p1,
        best_params_2  = final_p2,
        cv1_results    = cv1_df,
        cv2_results    = cv2_df,
        val_accuracy_1 = val_acc_1,
        val_accuracy_2 = final_v2,
        test_accuracy  = test_acc,
        y_pred         = y_pred,
        class_report   = cls_report,
        train_seconds  = elapsed,
    )


