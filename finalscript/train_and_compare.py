"""
train_and_compare.py
====================
Trains every model defined in a list of ModelSpec objects, runs two-round
staircase grid search for each one, and collects results into a ranked
comparison table with charts.

Architecture
------------
  train_and_export.py  →  prepare()  →  PreparedData
                       →  build_model_specs()  →  List[ModelSpec]
                       →  train_and_compare()  →  CompareResult

Two-round staircase grid search
--------------------------------
  Round 1  Coarse grid – wide, log-spaced or large-step ranges.
           Quickly locates the promising region of the hyperparameter space.
  Round 2  Fine grid   – generated by the per-spec refine_fn(best_params_1).
           Zooms in around the Round-1 optimum with smaller steps / tighter
           log-spacing to squeeze out the last fraction of performance.

Public API
----------
  specs   = build_model_specs()          # default specs; override in export
  result  = train_and_compare(data, specs, config)

  result.comparison_df                   # ranked DataFrame (test accuracy)
  result.train_results                   # List[TrainResult], one per model
  result.best_model_name                 # name of the highest-accuracy model
  result.summary()                       # print the ranked table

  # helpers exported for train_and_export.py
  zoom_int(center, step, n)              # fine int grid around a center value
  zoom_log(center, n, radius_decades)    # fine log grid around a center float

AI Usage
--------
This file was developed with the assistance of generative AI based on our previous work.
We ensured we understand and verify all AI-generated code, and we are responsible
for its correctness and suitability for our project.
"""

