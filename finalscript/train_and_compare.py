def zoom_int(center: int, step: int, n: int) -> np.ndarray:
    """
    Symmetric integer grid around *center*.

    Example
    -------
    zoom_int(97, 2, 5)  →  [89, 91, 93, 95, 97, 99, 101, 103, 105]
                             (5 steps left and right, step size 2)
    """
    radius = step * n
    arr = np.arange(max(1, center - radius), center + radius + 1, step)
    return arr


def zoom_log(center: float, n: int = 5, radius_decades: float = 1.0) -> np.ndarray:
    """
    Log-spaced grid of *2*n+1* values centred (in log10) on *center*.

    Example
    -------
    zoom_log(0.05, n=3, radius_decades=0.5)
    → 7 points from 10^(log10(0.05)-0.5) to 10^(log10(0.05)+0.5)
    """
    log_c = np.log10(center)
    return np.logspace(log_c - radius_decades, log_c + radius_decades, num=2 * n + 1)


